#ifndef SENSORS_H
#define SENSORS_H

#include <Arduino.h>

// ==========================================================
// هياكل بيانات الحساسات
// ==========================================================
typedef struct  {
    int left;
    int front;
    int right;
}IRReadings;

typedef struct {
    float gx, gy, gz;   // زوايا سرعة الدوران (deg/s)
    float ax, ay, az;   // التسارع (g)
    float yaw;          // الاتجاه المتراكم (deg) - من تكامل gz
} IMUData;

// ==========================================================
// دوال التهيئة
// ==========================================================
void sensors_init();

// ==========================================================
// قراءة حساسات الـ IR الثلاثة (مع إلغاء الضوء المحيط)
// ==========================================================
 IRReadings sensors_read_ir();

// ==========================================================
// قراءة الـ IMU (تسارع + جايروسكوب خام)
// ==========================================================
 IMUData sensors_read_imu();

// تحديث الـ yaw بتكامل الجايروسكوب - استدعيها كل loop بفارق الوقت dt بالثواني
void sensors_update_yaw(float dt);

// إرجاع آخر قيمة yaw متراكمة من غير إعادة قراءة الـ IMU
float sensors_get_yaw();

// تصفير الـ yaw (مفيد عند بداية كل تشغيلة أو بعد دورة 90 درجة)
void sensors_reset_yaw();

// معايرة الجايروسكوب وقت السكون (لازم الروبوت يكون واقف ساكن)
void sensors_calibrate_gyro();

#endif // SENSORS_H